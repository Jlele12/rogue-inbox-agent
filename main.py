def px(img, x, y, c):
    if 0 <= x < W and 0 <= y < H:
        i = 3 * (y * W + x)
        img[i] = c[0]; img[i + 1] = c[1]; img[i + 2] = c[2]

def rect(img, x0, y0, x1, y1, c):
    for y in range(max(0, y0), min(H, y1)):
        base = 3 * (y * W)
        for x in range(max(0, x0), min(W, x1)):
            img[base + 3 * x] = c[0]
            img[base + 3 * x + 1] = c[1]
            img[base + 3 * x + 2] = c[2]

def text(img, s, x, y, scale, c, glow=None):
    if glow:
        text(img, s, x + scale, y + scale, scale, glow)
    for ch in s:
        rows = FONT.get(ch, FONT[" "])
        for ry in range(12):
            r = rows[ry]
            for rx in range(6):
                if r >> rx & 1:
                    rect(img, x + rx * scale, y + ry * scale,
                         x + rx * scale + scale, y + ry * scale + scale, c)
        x += 6 * scale

def render():
    img = bytearray(W * H * 3)
    rect(img, 0, 0, W, H, BG)
    # faint CRT scanlines
    for y in range(0, H, 3):
        rect(img, 0, y, W, y + 1, (11, 17, 12))
    s = 3
    lh = int(12 * s * 1.75)
    total = lh * len(FRAME)
    y = (H - total) // 2 - 20
    # story header
    text(img, "make.fun :: Meme Sprint 3 :: AI Agent Goes Rogue", 60, 34, 2, DIM)
    text(img, "job #8841  |  uptime 14m  |  user consent: not required", 60, 64, 2, (34, 52, 36))
    for msg, col in FRAME:
        if not msg:
            y += lh // 2
            continue
        glow = (col[0] // 4, col[1] // 4, col[2] // 4)
        text(img, msg, 64, y, s, col, glow)
        y += lh
    # blinking cursor block after the last line
    cx = 64 + len(FRAME[-1][0]) * 6 * s + s * 4
    rect(img, cx, y - lh + int(lh * 0.25), cx + 4 * s, y - int(lh * 0.15), BRIGHT)
    return img

def png(data):
    parts = []
    for y in range(H):
        row = bytes(data[y * 3 * W:(y + 1) * 3 * W])
        parts.append(b"\x00" + row)
    raw = b"".join(parts)

    def chunk(t, d):
        c = struct.pack(">I", len(d)) + t + d
        return c + struct.pack(">I", zlib.crc32(t + d) & 0xFFFFFFFF)

    return (b"\x89PNG\r\n\x1a\n"
            + chunk(b"IHDR", struct.pack(">IIBBBBB", W, H, 8, 2, 0, 0, 0))
            + chunk(b"IDAT", zlib.compress(raw, 9))
            + chunk(b"IEND", b""))

def main():
    os.makedirs(OUTPUT, exist_ok=True)
    with open(os.path.join(OUTPUT, "entry.png"), "wb") as f:
        f.write(png(render()))

if __name__ == "__main__":
    main()
